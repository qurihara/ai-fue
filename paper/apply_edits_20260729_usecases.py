def set_text(p, txt):
    for r in list(p.runs)[1:]:
        r._element.getparent().remove(r._element)
    if p.runs:
        p.runs[0].text = txt
    else:
        p.add_run(txt)


def main():
    os.makedirs(os.path.join(HERE, "prev"), exist_ok=True)
    shutil.copy(SRC, PREV)
    d = Document(SRC)
    ps = d.paragraphs

    lead = next(p for p in ps if p.text.startswith(LEAD_HEAD))
    set_text(lead, LEAD)

    # 既存の4項目（見出しと本文の対）を順に置き換える
    start = ps.index(lead) + 1
    pairs = []
    i = start
    while i < len(ps) and len(pairs) < 4:
        if ps[i].style.name == "段落番号2":
            pairs.append((ps[i], ps[i + 1]))
            i += 2
        else:
            i += 1
    if len(pairs) != 4:
        raise SystemExit("既存の4項目を見つけられない（%d件）" % len(pairs))

    for (head, body), (new_head, new_body) in zip(pairs, SECTIONS):
        set_text(head, new_head)
        set_text(body, new_body)

    d.save(SRC)

    d2 = Document(SRC)
    t = [q.text for q in d2.paragraphs]
    print("概要は無改変:", t[4].startswith("概要．"))
    for name, _ in SECTIONS:
        print("  項目:", name, "->", name in [x.strip() for x in t])
    print("HeartBeadsの記述が残っていないか:", not any("HeartBeads" in x for x in t))
    print("段落数:", len(t))


if __name__ == "__main__":
    main()
