def set_cell(cell, text, header=False, size=7.5):
    cell.text = ""
    para = cell.paragraphs[0]
    para.paragraph_format.first_line_indent = Pt(0)
    para.paragraph_format.space_after = Pt(0)
    run = para.add_run(text)
    set_cjk(run, GOTHIC_EA if header else MINCHO_EA,
            ascii_="Arial" if header else "Century",
            size=size, bold=header)
    if header:
        shade_cell(cell, "D9D9D9")

def add_table(headers, rows, widths_in, size=7.5):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.autofit = False
    t.allow_autofit = False
    for ci, htext in enumerate(headers):
        set_cell(t.rows[0].cells[ci], htext, header=True, size=size)
    for row in rows:
        cells = t.add_row().cells
        for ci, val in enumerate(row):
            set_cell(cells[ci], val, header=False, size=size)
    # 列幅を全セルへ設定
    for ci, w in enumerate(widths_in):
        for cell in t.columns[ci].cells:
            cell.width = Inches(w)
    return t

