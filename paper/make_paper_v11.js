// PNGのIHDRから寸法を読み、段組幅(約300px)に合わせて縮尺した画像段落を返す。
function fig(file, widthPx = 300) {
  const p = path.join(__dirname, "figs", file);
  const buf = fs.readFileSync(p);
  const w = buf.readUInt32BE(16), h = buf.readUInt32BE(20);
  const scale = widthPx / w;
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 100, after: 20 },
    children: [new ImageRun({
      type: "png", data: buf,
      transformation: { width: Math.round(w * scale), height: Math.round(h * scale) },
    })],
  });
}

// ---- 表ヘルパ（列幅DXA配列＋2次元文字列。1行目はヘッダ） ----
function tbl(widths, rows) {
  const total = widths.reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((cells, ri) => new TableRow({
      children: cells.map((c, ci) => new TableCell({
        width: { size: widths[ci], type: WidthType.DXA },
        shading: ri === 0 ? { type: ShadingType.CLEAR, fill: "EEEEEE" } : undefined,
        margins: { top: 40, bottom: 40, left: 60, right: 60 },
        children: [new Paragraph({
          children: [new TextRun({ text: c, font: ri === 0 ? GOTHIC : MINCHO, size: 15, bold: ri === 0 })],
        })],
      })),
    })),
  });
}

